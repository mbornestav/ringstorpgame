const TABLES: Record<Lang, Record<Key, string>> = { en: EN, sv: SV };

function load(): Lang {
  try { return localStorage.getItem(LANG_KEY) === 'sv' ? 'sv' : 'en'; } catch { return 'en'; }
}
let current: Lang = load();
const listeners = new Set<() => void>();

export const getLang = (): Lang => current;
export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* private mode */ }
  for (const listener of listeners) listener();
}
export function onLangChange(listener: () => void): void { listeners.add(listener); }

/** Text for a key in the current language, with `{name}` placeholders filled from `params`. */
export function t(key: Key, params?: Params): string {
  const text = TABLES[current][key] ?? EN[key];
  return params ? text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`)) : text;
}
export const TABLE_KEYS = Object.keys(EN) as Key[];
export const tableFor = (lang: Lang): Record<Key, string> => TABLES[lang];
